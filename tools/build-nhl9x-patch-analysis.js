#!/usr/bin/env node
/**
 * Builds data/audio/nhl9x-patch-analysis.json: for each of the 32 NHL 93/94 FM patches, the decoded YM2612
 * parameters, where the songs and sounds use it, and measurements of a note rendered through the retail 68k + Z80
 * drivers and ymfm (envelope, brightness, noisiness; same measureNote as the NHL 92 analysis).
 *
 * The probe is a copy of the NHL 94 sound slice in which sound $0's event stream is replaced by one note on the
 * patch (patch event, key on, key off after 40 vblanks). The repo's drivers, patches and sound data are not changed.
 * Usage: node tools/build-nhl9x-patch-analysis.js [--check]
 */
'use strict';
const fs = require('fs');
const path = require('path');
const Song = require('../lib/audio/nhl9x-song');
const A = require('../lib/audio/nhl92-gm-analysis');
const Chain = require('../lib/audio/nhl92-sound-chain');
const ym = require('../lib/audio/ym2612-wasm');
const psg = require('../lib/audio/sn76489');
const driver = require('../lib/audio/nhl94-68k-harness');

const OUT = path.join(__dirname, '..', 'data', 'audio', 'nhl9x-patch-analysis.json');
const HOLD = 40, TAIL = 30;
const slice = (g) => fs.readFileSync(path.join(__dirname, '..', 'data', 'fixtures', 'nhl' + g + '-sound-slice.bin'));

function usage(g, sl) {
  const u = {};
  for (let id = 0; id < Song.GAMES[g].count; id++) {
    const r = Song.parse(g, sl, Song.streamAddr(g, sl, id));
    const cur = {};
    r.events.forEach((e) => {
      if (e.kind === 'patch') cur[e.ch] = e.patch;
      else if (e.kind === 'on') {
        const p = cur[e.ch] != null ? cur[e.ch] : 0;
        const x = u[p] || (u[p] = { notes: [], songs: new Set(), sfx: new Set(), channels: new Set() });
        x.notes.push(e.note);
        (id >= 0x30 ? x.songs : x.sfx).add(id);
        x.channels.add(e.ch);
      }
    });
  }
  return u;
}
const median = (a) => { const s = a.slice().sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };

async function build() {
  const sl94 = slice(94);
  const bank = Song.patches(94, sl94);
  const use = { 93: usage(93, slice(93)), 94: usage(94, sl94) };
  const start = Song.GAMES[94].start;
  const rom = new Uint8Array(0x4b5c0);
  rom.set(sl94, start);
  const addr = Song.streamAddr(94, sl94, 0);
  const patches = [];
  for (let p = 0; p < 32; p++) {
    const notes = [].concat((use[93][p] || { notes: [] }).notes, (use[94][p] || { notes: [] }).notes);
    const probe = notes.length ? median(notes) : 60;
    const ev = [0, 0xc0, p, 0, 0, 0x90, probe, 0x7f, HOLD, 0x80, probe, 0, 0x40, 0, 0xff, 0xff];
    const copy = rom.slice();
    copy.set(ev, addr);
    const chip = await ym.createChip();
    let pcm;
    try {
      const chain = Chain.create({ rom: copy, driver, chip, psg: psg.create(), keepLogs: false });
      chain.step(null);
      chain.step([{ sfx: 0 }]);
      for (let f = 2; f < HOLD + TAIL + 4; f++) chain.step(null);
      pcm = chain.take();
    } finally { chip.dispose(); }
    const hz = 440 * Math.pow(2, (probe - 69) / 12);
    const b = bank[p];
    const alg = b[28] & 7;
    const g = (g93) => { const x = use[g93][p]; return x ? { notes: x.notes.length, songs: x.songs.size, sfx: x.sfx.size, midiMin: Math.min.apply(null, x.notes), midiMax: Math.max.apply(null, x.notes), channels: Array.from(x.channels).sort((a1, b1) => a1 - b1) } : null; };
    patches.push({
      id: p,
      algorithm: alg,
      feedback: (b[28] >> 3) & 7,
      pan: b[29] >> 6, ams: (b[29] >> 4) & 3, fms: b[29] & 7,
      bendScale: b[30],
      operators: [0, 1, 2, 3].map((o) => ({ dt: (b[o] >> 4) & 7, mul: b[o] & 15, tl: b[4 + o], rs: b[8 + o] >> 6, ar: b[8 + o] & 31, am: b[12 + o] >> 7, d1r: b[12 + o] & 31, d2r: b[16 + o] & 31, sl: b[20 + o] >> 4, rr: b[20 + o] & 15 })),
      music: { nhl93: g(93), nhl94: g(94) },
      probe: { note: probe, hz: Math.round(hz * 10) / 10 },
      measured: A.measureNote(pcm, Chain.SAMPLE_RATE, hz, (HOLD * 1000) / Song.VBLANK_HZ)
    });
  }
  return {
    note: 'Generated by tools/build-nhl9x-patch-analysis.js from the bundled sound slices; do not edit by hand. The decisions about what each patch sounds like are in nhl9x-gm-map.json.',
    sampleRate: Chain.SAMPLE_RATE,
    method: 'Sound $0 of a copy of the NHL 94 slice is replaced by one note: patch select, key on at the median pitch the songs use (C4 if none), key off after ' + HOLD + ' vblanks, ' + TAIL + ' vblanks of tail; retail 68k + Z80 drivers, ymfm. Measurements as in nhl92-patch-analysis.json (5 ms RMS envelope, FFT 30 ms after onset).',
    patches
  };
}

if (require.main === module) {
  build().then((a) => {
    const text = JSON.stringify(a, null, 1) + '\n';
    if (process.argv.includes('--check')) {
      const old = JSON.parse(fs.readFileSync(OUT, 'utf8'));
      const ok = JSON.stringify(old.patches.map((p) => p.measured)) === JSON.stringify(a.patches.map((p) => p.measured));
      console.log(ok ? 'nhl9x patch analysis: up to date' : 'nhl9x patch analysis: differs');
      process.exit(ok ? 0 : 1);
    }
    fs.writeFileSync(OUT, text);
    console.log('wrote ' + OUT);
    a.patches.forEach((p) => console.log(String(p.id).padStart(2), p.measured.shape, 'att', p.measured.attackMs, 'k-off', p.measured.levelAtKeyOffDb, 'rel', p.measured.releaseMs, 'bright', p.measured.brightness, 'flat', p.measured.flatness, 'per', p.measured.periodicity, 'l100', p.measured.level100msDb, 'l400', p.measured.level400msDb));
  }).catch((e) => { console.error(e); process.exit(1); });
}
module.exports = { build };
