#!/usr/bin/env node
/**
 * Rebuild (or --check) the measurements behind the SNES instrument <-> GM maps:
 *   data/audio/nhl93s-instrument-analysis.json   NHLPA '93: 29 instruments, boot + game sample sets
 *   data/audio/nhl94s-sound-analysis.json        NHL '94: 56 menu-set and 29 game-set sound entries
 * Each entry is played once through the game's own SPC700 program and measured (lib/audio/snes-gm-analysis.js).
 *
 *   node tools/build-snes-gm-analysis.js            rewrite both files
 *   node tools/build-snes-gm-analysis.js --check    exit 1 if a committed file differs from a fresh run
 */
const fs = require('fs');
const path = require('path');
const A = require('../lib/audio/snes-gm-analysis');

const dir = path.join(__dirname, '..', 'data', 'audio');
const load = (n) => require(path.join(dir, n));
const jobs = [
  ['nhl93s-instrument-analysis.json', () => A.analyse93(require('../lib/audio/nhl93s-sound-data').load(load('nhl93s-sound.json'))), 'NHLPA 93 (SNES)'],
  ['nhl94s-sound-analysis.json', () => A.analyse94(require('../lib/audio/nhl94s-sound-data').load(load('nhl94s-sound.json'))), 'NHL 94 (SNES)']
];
const check = process.argv.includes('--check');
let bad = 0;
for (const [file, run, game] of jobs) {
  const doc = Object.assign({
    about: game + ': one probe note per instrument / sound entry, played through the game\'s own SPC700 program (held ' + A.HOLD_MS + ' ms, released) at the median pitch the retail songs use it at, and measured like the Genesis patches (lib/audio/nhl92-gm-analysis.js). Signal measurements, not listening. Generated by tools/build-snes-gm-analysis.js; do not edit.'
  }, run());
  const text = JSON.stringify(doc, null, 1) + '\n';
  const out = path.join(dir, file);
  if (check) {
    const same = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text;
    console.log(file + (same ? ' is up to date' : ' differs from a fresh run'));
    if (!same) bad = 1;
  } else {
    fs.writeFileSync(out, text);
    console.log('wrote data/audio/' + file + ' (' + text.length + ' chars)');
  }
}
process.exit(bad);
