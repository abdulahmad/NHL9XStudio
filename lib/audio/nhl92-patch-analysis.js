/**
 * Builds data/audio/nhl92-patch-analysis.json: for each of the 22 NHL '92 patches, the decoded
 * YM2612 parameters, where the five songs and the SFX use it, and measurements of a note
 * rendered through the step 4 pipeline (retail Z80 driver -> ymfm). Node only.
 *
 * The measurements describe the render (envelope, brightness, noisiness). The mapping file
 * (data/audio/nhl92-gm-map.json) is where a person decides what each patch sounds like.
 * Read-only: nothing here changes the drivers, the patches or the sound data.
 */
const audio = require('./nhl92-z80-audio');
const renders = require('./nhl92-chip-renders');
const sd = require('./nhl92-sound-data');
const fixture = require('./nhl92-sound-fixture');
const A = require('./nhl92-gm-analysis');

const HOLD_FRAMES = 40;
const TAIL_FRAMES = 30;
const DEFAULT_PROBE_INDEX = 48; // note-table index 48 = C4 = 261.6 Hz

const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const midiName = (m) => NOTE_NAMES[m % 12] + (Math.floor(m / 12) - 1);

async function build() {
  const rom = fixture.resolveRom(null);
  const data = sd.parse(rom);
  const usage = A.patchUsage(data);
  if (usage.warnings.length) throw new Error('usage walk warnings: ' + usage.warnings.join('; '));
  const sfx = A.sfxUsage(data);
  const src = renders.sources();
  const patches = [];
  for (const p of data.patches) {
    const u = usage.patches[p.id];
    // Probe at the pitch the songs use most (median), else C4. Index = MIDI - 12.
    const probeIndex = u.notes ? Math.round(u.midiMedian) - 12 : DEFAULT_PROBE_INDEX;
    const probeHz = 261.63 * Math.pow(2, (probeIndex - 48) / 12);
    const script = audio.patchScaleScript(src.rom, p.id, { notes: [probeIndex], hold: HOLD_FRAMES, gap: 2, tail: TAIL_FRAMES });
    const r = await renders.render(script, src);
    const decoded = A.decodePatch(p);
    patches.push({
      id: p.id,
      z80: '$' + p.z80.toString(16).toUpperCase().padStart(4, '0'),
      algorithm: decoded.algorithm,
      feedback: decoded.feedback,
      pan: decoded.pan,
      ams: decoded.ams,
      fms: decoded.fms,
      noteOffset: decoded.noteOffset,
      operators: decoded.operators,
      music: u.notes
        ? {
            notes: u.notes,
            frames: u.frames,
            songs: u.songs,
            midiMin: u.midiMin,
            midiMax: u.midiMax,
            midiMedian: u.midiMedian,
            distinctPitches: u.distinctPitches,
            channels: u.channels
          }
        : null,
      sfx: sfx[p.id],
      probe: { index: probeIndex, midi: probeIndex + 12, name: midiName(probeIndex + 12), hz: Math.round(probeHz * 10) / 10 },
      measured: A.measureNote(r.pcm, audio.SAMPLE_RATE, probeHz, (HOLD_FRAMES * 1000) / 60)
    });
  }
  return {
    note: 'Generated by tools/build-nhl92-patch-analysis.js from the bundled sound slice; do not edit by hand. ' +
      'The decisions about what each patch sounds like are in nhl92-gm-map.json.',
    sampleRate: audio.SAMPLE_RATE,
    method: {
      decode: 'Z80 register order $30,$38,$34,$3C,... (Z80 $00C5): within a group the operators are op1, op2, op3, op4.',
      music: 'Each channel\'s order list walked once (repeats expanded, stopping at the first restart or song switch); pitch is MIDI = note index + 12 after the patch note offset and transpose; frames = duration units x song tempo.',
      sfx: 'FM SFX streams that load the patch with $80 id; SFX IDs as the game passes them.',
      probe: 'One note held ' + HOLD_FRAMES + ' frames (' + Math.round((HOLD_FRAMES * 1000) / 60) + ' ms) then released, at the patch\'s median song pitch (C4 if no song uses it), rendered by the step 4 pipeline. Envelope from 5 ms RMS windows; spectrum from a 4096-point FFT 30 ms after onset; flatness over 40 Hz-16 kHz (0 = tonal, 1 = noise); periodicity = best normalised autocorrelation 25 Hz-4 kHz.'
    },
    patches
  };
}

/** Pretty JSON that keeps small leaf objects/arrays on one line (readable operator tables). */
function format(value, indent) {
  const pad = '  '.repeat(indent);
  const flat = JSON.stringify(value);
  if (value === null || typeof value !== 'object') return flat;
  if (flat.length <= 110 || (Array.isArray(value) && value.every((v) => v === null || typeof v !== 'object'))) return flat;
  if (Array.isArray(value)) {
    return '[\n' + value.map((v) => pad + '  ' + format(v, indent + 1)).join(',\n') + '\n' + pad + ']';
  }
  return '{\n' + Object.keys(value).map((k) => pad + '  ' + JSON.stringify(k) + ': ' + format(value[k], indent + 1)).join(',\n') + '\n' + pad + '}';
}

function stringify(analysis) {
  return format(analysis, 0) + '\n';
}

const TOL = { attackMs: 10, peakMs: 10, level100msDb: 2, level400msDb: 2, levelAtKeyOffDb: 2, releaseMs: 10, centroidHz: 0.1, centroidLateHz: 0.1, brightness: 0.1, flatness: 0.05, periodicity: 0.05 };

/** Differences between a stored analysis and a fresh one. Structure must match exactly; measured values within TOL. */
function compare(stored, fresh) {
  const problems = [];
  const strip = (a) => JSON.stringify(a.patches.map((p) => Object.assign({}, p, { measured: undefined })));
  if (strip(stored) !== strip(fresh)) problems.push('decoded parameters / usage / probe differ');
  stored.patches.forEach((p, i) => {
    const q = fresh.patches[i];
    if (!q) return;
    for (const k of Object.keys(TOL)) {
      const a = p.measured[k];
      const b = q.measured[k];
      if (a == null || b == null) { if (a !== b) problems.push('patch ' + p.id + ' ' + k + ': ' + a + ' vs ' + b); continue; }
      const tol = k === 'centroidHz' || k === 'centroidLateHz' ? Math.max(50, Math.abs(a) * TOL[k]) : k === 'brightness' ? Math.max(0.2, Math.abs(a) * TOL[k]) : TOL[k];
      if (Math.abs(a - b) > tol) problems.push('patch ' + p.id + ' ' + k + ': ' + a + ' vs ' + b);
    }
    if (p.measured.shape !== q.measured.shape) problems.push('patch ' + p.id + ' shape: ' + p.measured.shape + ' vs ' + q.measured.shape);
  });
  return problems;
}

module.exports = { build, stringify, compare, midiName, HOLD_FRAMES };
